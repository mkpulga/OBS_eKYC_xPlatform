using System.Globalization;

namespace OBS.Core;
public enum ListExportScope { SelectedRecord, CurrentPage, AllFilteredRecords }
public sealed class ReportContract
{
    public string Module { get; }
    public string OperatorEmail { get; }
    public DateTimeOffset GeneratedAt { get; }
    public ListExportScope Scope { get; }
    public string Timestamp => GeneratedAt.ToOffset(TimeSpan.FromHours(8)).ToString("yyyy-MM-dd HH:mm:ss 'UTC+08:00'", CultureInfo.InvariantCulture);
    public ReportContract(string module, string operatorEmail, DateTimeOffset generatedAt, ListExportScope scope, bool completeFilteredDataset)
    {
        if (string.IsNullOrWhiteSpace(module) || string.IsNullOrWhiteSpace(operatorEmail)) throw new ArgumentException("Module and operator email are required.");
        if (!Enum.IsDefined(scope)) throw new ArgumentException("Unknown export scope.");
        if (scope == ListExportScope.AllFilteredRecords && !completeFilteredDataset)
            throw new InvalidOperationException("All filtered records export requires a verified complete filtered dataset.");
        Module = module; OperatorEmail = operatorEmail; GeneratedAt = generatedAt; Scope = scope;
    }
    private string Prefix => $"{Module} – Generated by {OperatorEmail} | {Timestamp} | Page ";
    public string PageFooter(int page, int totalPages)
    {
        if (page < 1 || totalPages < page) throw new ArgumentOutOfRangeException(nameof(page));
        return Prefix + $"{page} of {totalPages}";
    }
    // Spreadsheet page fields are evaluated by the application's print preview/print engine.
    public string ExcelPrintFooter => Prefix.Replace("&", "&&", StringComparison.Ordinal) + "&P of &N";
    // Word exporters must emit PAGE and NUMPAGES fields, not literal text pretending to know pagination.
    public string WordFooterPrefix => Prefix;
}
